export function StaticColliders() {
  return (
    <>
      {COLLIDERS.map((b, i) => {
        const cx = (b.min[0] + b.max[0]) / 2, cy = (b.min[1] + b.max[1]) / 2, cz = (b.min[2] + b.max[2]) / 2;
        const hx = (b.max[0] - b.min[0]) / 2, hy = (b.max[1] - b.min[1]) / 2, hz = (b.max[2] - b.min[2]) / 2;
        return (
          <RigidBody key={i} type="fixed" colliders={false} position={[cx, cy, cz]}>
            <CuboidCollider args={[hx, hy, hz]} />
          </RigidBody>
        );
      })}
    </>
  );
}

